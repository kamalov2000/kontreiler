import { Order } from '@/types/database'

/**
 * Условия оплаты по рейсу — часть коммерческого предложения наравне со ставкой.
 *
 * Хранятся свободным текстом: «5 банковских дней по оригиналам», «предоплата
 * топливом 50%», «оплата на выгрузке», «только по прямому договору» — любой
 * закрытый список пришлось бы дополнять каждую неделю. Кнопки ниже закрывают
 * частые случаи, чтобы не набирать руками.
 */
export const PAYMENT_TERMS_PRESETS: string[] = [
  '3 банковских дня',
  '5 банковских дней',
  '7 банковских дней',
  '10 банковских дней',
  '14 банковских дней',
  'Оплата на выгрузке',
  'Предоплата 50%',
  'Предоплата топливом',
]

/**
 * Условия, действующие по рейсу: согласованные, если стороны их меняли, иначе
 * заявленные в заявке. Ровно как effectiveDowntimeRate для ставки простоя.
 */
export function effectivePaymentTerms(
  order: Pick<Order, 'payment_terms' | 'agreed_payment_terms'> | null | undefined,
): string | null {
  return order?.agreed_payment_terms?.trim() || order?.payment_terms?.trim() || null
}
