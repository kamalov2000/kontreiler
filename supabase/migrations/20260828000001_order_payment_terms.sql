-- Условия оплаты в заявке — часть коммерческого предложения.
--
-- «Через сколько банковских дней платят, предоплата деньгами или топливом,
-- оплата на выгрузке, работа по прямому договору» — по этому перевозчик решает,
-- брать рейс или нет, не меньше чем по ставке. Раньше это писали в комментарии
-- или выясняли в чате.
--
-- Поле свободным текстом, а не списком: условия оплаты у всех разные, любой
-- перечень пришлось бы дополнять каждую неделю. В форме к нему приложены
-- кнопки-заготовки на частые случаи.
--
-- Две колонки, как у price/agreed_price, и ровно по той же причине:
--   payment_terms        — условие, опубликованное в заявке (оффер);
--   agreed_payment_terms — то, о чём стороны договорились, уходит в
--                          договор-заявку.
-- В заявке было 10 дней, сторговались на 5 — оффер остаётся историей, в
-- документ идёт согласованное. Пусто = договорились по заявке.

ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS payment_terms        TEXT;
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS agreed_payment_terms TEXT;
