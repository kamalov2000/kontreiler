-- Пакет рейсов: одна публикация — несколько контейнеров по одному маршруту.
--
-- Раньше клиент с десятью контейнерами создавал десять почти одинаковых заявок
-- копированием, и лента забивалась дублями. Теперь при публикации создаётся N
-- самостоятельных заявок с общим batch_id: у каждой свой номер КТ-XXXXX, свой
-- контейнер и своя судьба (номинация, ТН, договор-заявка — без изменений).
-- Пакет — только способ показа: лента и дашборд схлопывают такие заявки в одну
-- карточку, реестр перевозок про batch_id ничего не знает и берёт их построчно.
--
-- Отдельной таблицы пакета нет намеренно: у пакета нет собственного состояния —
-- «свободно N из M» считается по статусам самих заявок.

ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS batch_id UUID;

-- Частичный: заявок вне пакета в таблице подавляющее большинство, в индексе им
-- делать нечего.
CREATE INDEX IF NOT EXISTS idx_orders_batch ON public.orders (batch_id) WHERE batch_id IS NOT NULL;

-- ЗПУ (номер пломбы) — как и номер контейнера, у каждого рейса пакета свой.
-- До этого поле жило только в форме транспортной накладной и в заявке не
-- хранилось: клиенту негде было записать пломбу заранее.
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS seal_number TEXT;
